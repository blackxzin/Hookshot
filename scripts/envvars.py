"""List the environment variables the code reads, with where, as docs/env-vars.md.

    python -I scripts/envvars.py            # write docs/env-vars.md
    python -I scripts/envvars.py --check    # exit 1 if the file is out of date (CI)

Scans getenv("X") in C/C++ and os.environ / os.getenv in Python under host, gpu/vk, gpu/render, nx2 and scripts
(not the vendored Eden, sirit or compat code). The note is the comment on the same line, when there is one.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = ["host", "gpu/vk", "gpu/render", "nx2", "scripts"]
SKIP = ("gpu/vk/eden", "gpu/vk/sirit", "gpu/vk/compat", "gpu/vk/host_shaders", "nx2/rt")
EXT = (".c", ".cpp", ".h", ".hpp", ".py")
C_PAT = re.compile(r'getenv\(\s*"([A-Z][A-Z0-9_]+)"')
PY_PAT = re.compile(r'(?:environ(?:\.get)?\s*[\[(]|getenv\()\s*["\']([A-Z][A-Z0-9_]+)["\']')
NOTE_PAT = re.compile(r"(?://|/\*|#)\s*\(?(.*?)\)?\s*(?:\*/)?\s*$")
OUT = os.path.join(ROOT, "docs", "env-vars.md")


def files():
    for d in DIRS:
        for base, _, names in os.walk(os.path.join(ROOT, d)):
            rel = os.path.relpath(base, ROOT).replace(os.sep, "/")
            if rel.startswith(SKIP):
                continue
            for n in sorted(names):
                if n.endswith(EXT):
                    yield rel + "/" + n


def scan():
    found = {}
    for rel in sorted(files()):
        pat = PY_PAT if rel.endswith(".py") else C_PAT
        with open(os.path.join(ROOT, rel), encoding="utf-8", errors="replace") as f:
            for no, line in enumerate(f, 1):
                for name in pat.findall(line):
                    e = found.setdefault(name, {"first": (rel, no), "files": set(), "note": ""})
                    e["files"].add(rel)
                    if not e["note"]:
                        m = NOTE_PAT.search(line.split(name, 1)[1]) if ("//" in line or "/*" in line or "#" in line) else None
                        note = m.group(1).strip() if m else ""
                        if note and not note.startswith(("(", ")")) and len(note) > 3:
                            e["note"] = note.replace("|", "\\|")[:110]
    return found


def render(found):
    out = ["# Environment variables", "",
           "Generated by `python -I scripts/envvars.py`; do not edit by hand. These are switches for testing and",
           "diagnostics. Put them in `hookshot_env.txt` beside the game, one `NAME=VALUE` a line. Most are not",
           "supported options: read the code at the place named before you rely on one.", "",
           "| Variable | First read | Files | Note |", "|---|---|---|---|"]
    for name in sorted(found):
        e = found[name]
        rel, no = e["first"]
        out.append("| `%s` | `%s:%d` | %d | %s |" % (name, rel, no, len(e["files"]), e["note"]))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(scan())
    if a.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("docs/env-vars.md is out of date: run python -I scripts/envvars.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d variables)" % (os.path.relpath(OUT, ROOT), text.count("\n| `")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
